#!/data/data/com.termux/files/usr/bin/bash
set -euo pipefail

cd "$(dirname "$0")"

ROOT="$PWD"

gen_one() {
	local dir="$1"
	local rel="${dir#"$ROOT"}"
	rel="${rel#/}"
	[ -z "$rel" ] && rel="."

	local idx="$dir/index.html"
	local display
	if [ "$rel" = "." ]; then
		display="/"
	else
		display="/$rel/"
	fi

	{
		echo '<!DOCTYPE html>'
		echo '<html><head><meta charset="utf-8">'
		echo "<title>Directory listening for $display</title>"
		echo '<style>'
		echo 'body{font-family:monospace;margin:2em;color:#222}'
		echo 'h1{font-size:1.5em;border-bottom:1px solid #ccc;padding-bottom:.3em}'
		echo 'ul{list-style:none;padding-left:0}'
		echo 'li{margin:4px 0}'
		echo 'a{text-decoration:none;color:#0366d6}'
		echo 'a:hover{text-decoration:underline}'
		echo 'span.size{color:#888;font-size:90%}'
		echo '</style>'
		echo '</head><body>'
		echo "<h1>Directory listening for $display</h1>"
		echo '<ul>'
		if [ "$rel" != "." ]; then
			echo '<li>📂 <a href="../">../</a></li>'
		fi
		while IFS= read -r entry; do
			local name base
			name="$dir/$entry"
			base="$entry"
			if [ "$entry" = "index.html" ]; then
				continue
			fi
			if [ -d "$name" ]; then
				echo "<li>📂 <a href=\"$base/\">$base/</a></li>"
			else
				local size
				size=$(stat -c %s "$name" 2>/dev/null || echo "")
				if [ -n "$size" ]; then
					echo "<li>📄 <a href=\"$base\">$base</a> <span class=\"size\">($size B)</span></li>"
				else
					echo "<li>📄 <a href=\"$base\">$base</a></li>"
				fi
			fi
		done < <(
			{
				find "$dir" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' 2>/dev/null || \
					ls -1p "$dir" | grep '/$' | sed 's:/$::'
			} | sort
			{
				find "$dir" -mindepth 1 -maxdepth 1 -type f -printf '%f\n' 2>/dev/null || \
					ls -1p "$dir" | grep -v '/$'
			} | sort
		)
		echo '</ul>'
		echo '<p style="color:#888;font-size:85%">Generated by gen-index.sh</p>'
		echo '</body></html>'
	} > "$idx"
}

find "$ROOT" -type d -not -path '*/.git*' | while IFS= read -r d; do
	gen_one "$d"
done

echo "done: index.html generated in all dirs"
